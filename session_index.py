"""
Regenerate a repository's session index from its session records.

    python session_index.py <repository root>

Each record is `sessions/<date>-<short-sha>.md`. The index, `sessions/INDEX.md`, is
one table row per record, newest first: the date, and the record's first heading
as a link to it. A leading "Session <n> ·" and a repeated date are dropped from the
heading, so older numbered records read like newer unnumbered ones.

The index is generated, never edited by hand; run this after writing a record.
It uses the Python standard library alone.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

RECORD = re.compile(r"^(\d{4}-\d{2}-\d{2})-[0-9a-f]{4,40}\.md$")
PREFIX = re.compile(r"^(Session\s+\d+\s*[·:.-]\s*)?(\d{4}-\d{2}-\d{2}\s*[—–-]\s*)?")

HEADER = """# Session index

Generated by `session_index.py` from each record's first heading; not edited by hand.
Open a record only to look up something specific from a past session, or to review a
session just completed.

| date | record |
|---|---|
"""


def title(path: Path) -> str:
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("# "):
            text = PREFIX.sub("", line[2:].strip()).strip()
            return text.replace("|", "\\|") or path.stem
    return path.stem


def build(root: Path) -> str:
    folder = root / "sessions"
    records = sorted((p for p in folder.iterdir() if RECORD.match(p.name)),
                     key=lambda p: (RECORD.match(p.name).group(1), p.name),
                     reverse=True)
    rows = [f"| {RECORD.match(p.name).group(1)} | [{title(p)}](./{p.name}) |"
            for p in records]
    return HEADER + "".join(row + "\n" for row in rows)


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        print(__doc__.strip().splitlines()[0], file=sys.stderr)
        print("usage: python session_index.py <repository root>", file=sys.stderr)
        return 2
    root = Path(args[0])
    if not (root / "sessions").is_dir():
        print(f"no sessions/ folder under {root}", file=sys.stderr)
        return 2
    (root / "sessions" / "INDEX.md").write_text(build(root), encoding="utf-8",
                                                newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
