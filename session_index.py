"""
Regenerate a repository's session index from its session records.

    python session_index.py <repository root>
    python session_index.py --check <repository root>

Each record is `sessions/<date>-<id>.md`. The index, `sessions/INDEX.md`, is a table
with one row per session, newest first: `| # | date | label | block | found |`.

A record written to the current format generates its own row. It opens with

    # Session <n>: <label>

and carries a `**Block:**` line (the block's name, up to the first ` · `) and one
`**Found:**` line, the one-line summary of what the session found. All three are
needed; a record missing any of them is treated as an older record.

An older record's row is kept exactly as it stands in the index, because records are
born final and their rows were final when written. An older record with no row gets one
from its first heading: a leading "Session <n>" goes to the `#` column, and a repeated
date is dropped from the label. A row that names no record file is kept as it stands.

Everything above the table (the index's own preamble) is kept as it stands, and so are
the table's own column names and order, where they are the five columns under any of
their known names. A table in the earlier two-column format (`| date | record |`) is
widened to the five columns, its rows keeping their date and record and gaining empty
cells. A missing index is written with a default preamble.

`--check` writes nothing: it exits 1 and prints the difference if the index would
change or names the columns if they are not the standard five in the standard order,
and exits 0 otherwise. It uses the Python standard library alone.
"""
from __future__ import annotations

import difflib
import re
import sys
from pathlib import Path

RECORD = re.compile(r"^(\d{4}-\d{2}-\d{2})-[0-9A-Za-z-]+\.md$")
DATE_OF = re.compile(r"^(\d{4}-\d{2}-\d{2})-")
PREFIX = re.compile(r"^(Session\s+(\d+)\s*[·:.-]\s*)?(\d{4}-\d{2}-\d{2}\s*[—–-]\s*)?")
CURRENT_HEADING = re.compile(r"^#\s+Session\s+(\d+):\s*(.+?)\s*$")
BLOCK_LINE = re.compile(r"^\*\*Block:\*\*\s*(.+?)\s*$")
FOUND_LINE = re.compile(r"^\*\*Found:\*\*\s*(.+?)\s*$")
LINK = re.compile(r"\]\((?:\./)?([^)\s]+\.md)\)")

KEYS = ("number", "date", "label", "block", "found")
DEFAULT_COLUMNS = ["#", "date", "label", "block", "found"]
ALIASES = {
    "#": "number", "number": "number", "n": "number",
    "date": "date",
    "label": "label", "record": "label", "title": "label",
    "block": "block",
    "found": "found", "what it found": "found",
}

DEFAULT_PREAMBLE = """# Session index

One record per session, newest first. A session is a unit of work, not a sitting. Numbers
are taken from this table, the highest plus one, and never reused. Rows are generated by
`session_index.py`; nothing here is typed. Open a record only to look up something
specific from a past session, or to review a session just completed.

"""


def cells(line: str) -> list[str]:
    """The cells of a table row, splitting on pipes that are not escaped."""
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|") and not body.endswith("\\|"):
        body = body[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", body)]


def is_separator(line: str) -> bool:
    return bool(re.fullmatch(r"\|?(\s*:?-{3,}:?\s*\|)+\s*:?-{0,}:?\s*\|?", line.strip()))


def parse_index(text: str):
    """Split an index into preamble, column names, rows (as raw lines) and tail."""
    lines = text.splitlines()
    for i in range(len(lines) - 1):
        if lines[i].lstrip().startswith("|") and is_separator(lines[i + 1]):
            j = i + 2
            while j < len(lines) and lines[j].lstrip().startswith("|"):
                j += 1
            preamble = "\n".join(lines[:i]) + "\n"
            tail = "\n".join(lines[j:])
            return preamble, cells(lines[i]), lines[i + 2:j], tail
    return None


def heading(path: Path) -> str:
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def current_fields(path: Path) -> dict | None:
    """The five fields of a record written to the current format, or None."""
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    head = next((l for l in lines if l.startswith("# ")), "")
    m = CURRENT_HEADING.match(head)
    block = next((BLOCK_LINE.match(l) for l in lines if BLOCK_LINE.match(l)), None)
    found = next((FOUND_LINE.match(l) for l in lines if FOUND_LINE.match(l)), None)
    if not (m and block and found):
        return None
    return {"number": m.group(1), "date": DATE_OF.match(path.name).group(1),
            "label": m.group(2), "block": block.group(1).split(" · ")[0].strip(),
            "found": found.group(1)}


def fallback_fields(path: Path) -> dict:
    """Fields for an older record that has no row: from its first heading only."""
    text = heading(path)
    m = PREFIX.match(text)
    number = m.group(2) or ""
    label = PREFIX.sub("", text).strip() or path.stem
    return {"number": number, "date": DATE_OF.match(path.name).group(1),
            "label": label, "block": "", "found": ""}


def esc(value: str) -> str:
    return value.replace("|", "\\|")


def render(fields: dict, name: str, keys: list[str], bare: bool) -> str:
    link = name if bare else "./" + name
    out = []
    for key in keys:
        value = fields.get(key, "")
        if key == "label":
            value = f"[{esc(value)}]({link})"
        else:
            value = esc(value)
        out.append(value)
    return "| " + " | ".join(out) + " |"


def sort_key(fields_date: str, number: str):
    return (fields_date, int(number) if number.isdigit() else -1)


def build(root: Path) -> str:
    folder = root / "sessions"
    index = folder / "INDEX.md"
    records = sorted(p for p in folder.iterdir() if RECORD.match(p.name))

    preamble, columns, raw_rows, tail = DEFAULT_PREAMBLE, list(DEFAULT_COLUMNS), [], ""
    widen = False
    if index.exists():
        parsed = parse_index(index.read_text(encoding="utf-8"))
        if parsed:
            preamble, columns, raw_rows, tail = parsed
            known = [ALIASES.get(c.lower()) for c in columns]
            if sorted(k for k in known if k) == sorted(KEYS) and len(columns) == 5:
                pass
            elif [k for k in known] == ["date", "label"]:
                widen, columns = True, list(DEFAULT_COLUMNS)
            else:
                raise ValueError(f"{index}: unrecognised columns {columns}")
    keys = [ALIASES[c.lower()] for c in columns]

    existing: dict[str, str] = {}
    orphans: list[tuple] = []
    links_bare = 0
    for pos, line in enumerate(raw_rows):
        row = cells(line)
        if widen:
            row = ["", row[0], row[1] if len(row) > 1 else "", "", ""]
            line = "| " + " | ".join(row) + " |"
        values = dict(zip(keys, row))
        m = LINK.search(values.get("label", ""))
        if m and "](./" not in values.get("label", ""):
            links_bare += 1
        if m and RECORD.match(Path(m.group(1)).name) and (folder / m.group(1)).exists():
            existing[m.group(1)] = line
        else:
            orphans.append((sort_key(values.get("date", ""), values.get("number", "")), pos, line))
    bare = links_bare > len(raw_rows) / 2

    rows: list[tuple] = list(orphans)
    for path in records:
        fields = current_fields(path)
        if fields:
            line = render(fields, path.name, keys, bare)
            key = sort_key(fields["date"], fields["number"])
        elif path.name in existing:
            line = existing[path.name]
            values = dict(zip(keys, cells(line)))
            key = sort_key(values.get("date", ""), values.get("number", ""))
        else:
            fields = fallback_fields(path)
            line = render(fields, path.name, keys, bare)
            key = sort_key(fields["date"], fields["number"])
        position = next((i for i, l in enumerate(raw_rows) if path.name in l), len(raw_rows))
        rows.append((key, position, line))

    # newest first; rows already in the index keep their order among equals
    rows.sort(key=lambda r: (r[0], -r[1]), reverse=True)
    table = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    out = preamble + "\n".join(table + [r[2] for r in rows]) + "\n"
    if tail.strip():
        out += tail.rstrip("\n") + "\n"
    return out


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    if len(args) != 1:
        print(__doc__.strip().splitlines()[0], file=sys.stderr)
        print("usage: python session_index.py [--check] <repository root>", file=sys.stderr)
        return 2
    root = Path(args[0])
    if not (root / "sessions").is_dir():
        print(f"no sessions/ folder under {root}", file=sys.stderr)
        return 2
    index = root / "sessions" / "INDEX.md"
    try:
        new = build(root)
    except ValueError as err:
        print(err, file=sys.stderr)
        return 2
    if check:
        # A Windows console or pipe defaults to a code page that cannot show every character.
        reconfigure = getattr(sys.stdout, "reconfigure", None)
        if reconfigure:
            reconfigure(encoding="utf-8", errors="replace")
        old = index.read_text(encoding="utf-8") if index.exists() else ""
        parsed = parse_index(old) if old else None
        if parsed and parsed[1] != DEFAULT_COLUMNS:
            print(f"{index}: the columns are {parsed[1]}; the standard is {DEFAULT_COLUMNS}")
            return 1
        if old == new:
            return 0
        sys.stdout.writelines(difflib.unified_diff(
            old.splitlines(keepends=True), new.splitlines(keepends=True),
            "INDEX.md (now)", "INDEX.md (generated)"))
        return 1
    index.write_text(new, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
